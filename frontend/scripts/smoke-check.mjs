import assert from 'node:assert/strict';
import { api } from '../src/lib/api.js';
import { TX_STATES, ITEM_STATES, PAYMENT_STATES, LOT_MONEY_STATES, INSTRUCTION_STATES, money } from '../src/lib/constants.js';

assert.deepEqual(TX_STATES, ['DRAFT','AWAITING_BUYER_AGREEMENT','AWAITING_PAYMENT','FUNDED','COMPLETED','CANCELLED','EXPIRED']);
assert.ok(ITEM_STATES.includes('RETURN_HANDOVER_RECORDED'));
assert.ok(PAYMENT_STATES.includes('PAYMENT_RECEIVED'));
assert.ok(LOT_MONEY_STATES.includes('REFUND_PENDING'));
assert.ok(INSTRUCTION_STATES.includes('PENDING_APPROVAL'));
assert.match(money(110000000), /1,100,000/);

api.reset();
api.switchRole('BUYER');
const autoKeyPayment=await api.action('/transactions/tx_a210/payments',{});
assert.equal(autoKeyPayment.status,'PENDING','the API layer supplies a mandatory idempotency key for POST requests');
assert.equal((await api.transaction('tx_a210')).payments.length,1);
api.reset();
api.switchRole('BUYER');
const buyerTransactions = await api.listTransactions('BUYER');
assert.equal(buyerTransactions.items.length, 5, 'buyer sees only transactions where they are a party');
const payment = await api.action('/transactions/tx_a210/payments', {}, {'Idempotency-Key':'smoke-test-idempotency-key'});
assert.equal(payment.status, 'PENDING');
const duplicatePayment=await api.action('/transactions/tx_a210/payments',{}, {'Idempotency-Key':'smoke-test-idempotency-key'});
assert.equal(duplicatePayment.payment_id,payment.payment_id,'same idempotency key returns the original attempt');
assert.equal((await api.transaction('tx_a210')).payments.length,1,'duplicate payment submissions do not create another payment attempt');
await assert.rejects(()=>api.action('/transactions/tx_a210/payments',{different_body:true},{'Idempotency-Key':'smoke-test-idempotency-key'}),e=>e?.data?.error?.code==='IDEMPOTENCY_KEY_REUSED');
const afterPayment = await api.transaction('tx_a210');
assert.equal(afterPayment.status, 'AWAITING_PAYMENT', 'pending payment must not mark funds secured');
assert.equal(afterPayment.payments.at(-1).status, 'PENDING');
const file = new File(['SupplyKey evidence'], 'evidence.jpg', {type:'image/jpeg'});
// The mock adapter intentionally mirrors the API's evidence upload completion response.
const upload = await api.upload(file, 'OTHER', 'tx_a210');
assert.equal(upload.status, 'VERIFIED');
api.switchRole('SUPPLIER');
const dispatchEvidence = await api.upload(file, 'DISPATCH', 'tx_7f42');
await api.action('/transactions/tx_7f42/dispatch', {lines:[{item_id:'it_4',quantity:1}],courier_name:'Demo Courier',rider_name:'Demo Rider',rider_phone:'+2348000000000',evidence_ids:[dispatchEvidence.id]});
const dispatched = await api.transaction('tx_7f42');
assert.equal(dispatched.status, 'FUNDED', 'dispatch must not replace the canonical transaction status');
assert.ok(dispatched.lots.some(l=>l.item_status==='DISPATCHED'&&l.quantity===1));
assert.ok(dispatched.lots.some(l=>l.item_status==='AWAITING_DISPATCH'&&l.quantity===1), 'partial dispatch preserves the undispatched quantity');
api.switchRole('BUYER');
await api.action('/transactions/tx_7f42/delivery/confirm-received', {lines:[{item_id:'it_4',quantity:1}]});
const receipt = await api.transaction('tx_7f42');
assert.equal(receipt.status, 'FUNDED');
assert.ok(receipt.lots.some(l=>l.item_status==='RECEIPT_CONFIRMED'&&l.quantity===1));
assert.ok(receipt.lots.some(l=>l.item_status==='AWAITING_DISPATCH'&&l.quantity===1));
const buyerReq=receipt.delivery_photo_requirements.find(r=>r.party_role==='BUYER');
const rejectionProof=await api.upload(file,'REJECTION_PROOF','tx_7f42');
await assert.rejects(()=>api.action('/transactions/tx_7f42/decisions',{lines:[{item_id:'it_4',quantity_submitted:1,quantity_accepted:0,quantity_rejected:1,reject:{agreed_condition_ids:['c_5'],reason_text:'The returned camera does not match the agreed specification.',evidence_ids:[rejectionProof.id]}}]}),e=>e?.data?.error?.code==='DELIVERY_PHOTOS_REQUIRED');
const buyerPhoto=await api.upload(file,'DELIVERY_PHOTO','tx_7f42');
await api.action('/transactions/tx_7f42/delivery/evidence',{requirement_id:buyerReq.id,evidence_ids:[buyerPhoto.id],note:'Demo buyer delivery photographs.'});
await api.action('/transactions/tx_7f42/decisions',{lines:[{item_id:'it_4',quantity_submitted:1,quantity_accepted:0,quantity_rejected:1,reject:{agreed_condition_ids:['c_5'],reason_text:'The returned camera does not match the agreed specification.',evidence_ids:[rejectionProof.id]}}]});
await api.action('/transactions/tx_7f42/returns',{lines:[{item_id:'it_4',quantity:1}]});
const returnId=(await api.transaction('tx_7f42')).return_id;
const handoverPhoto=await api.upload(file,'RETURN_HANDOVER','tx_7f42');
await api.action(`/returns/${returnId}/handover-evidence`,{evidence_ids:[handoverPhoto.id],courier_name:'Demo Courier',rider_name:'Demo Rider',rider_phone:'+2348000000000',tracking_ref:'RET-001'});
api.switchRole('SUPPLIER');
const returnReceiptPhoto=await api.upload(file,'RETURN_RECEIPT','tx_7f42');
await api.action(`/returns/${returnId}/confirm-receipt`,{lines:[{item_id:'it_4',quantity_received:1,condition_matches_original:true}],evidence_ids:[returnReceiptPhoto.id],note:'Returned unit received.'});
const refundInstructions=await api.financialInstructions('tx_7f42','refunds');
assert.equal(refundInstructions.length,1);assert.equal(refundInstructions[0].status,'QUEUED');
assert.equal((await api.transaction('tx_7f42')).status,'FUNDED','return confirmation creates an instruction, not an automatic refund or completed transaction');
api.switchRole('MODERATOR');
const queue = await api.moderatorQueue();
assert.equal(queue.items.length, 2);
const reviewFile=await api.decisionDetail('dec_1');assert.equal(reviewFile.decision.id,'dec_1');
const disputeFile=await api.caseDetail('dis_31');assert.equal(disputeFile.dispute.id,'dis_31');
const confirmation = await api.action('/mod/decisions/dec_1/confirm', {reason:'The evidence and agreement have been reviewed and the accepted quantity meets the recorded conditions.',evidence_ids_considered:[]});
assert.equal(confirmation.payout.status, 'PENDING_APPROVAL', 'high-value payout requires a second approval');
const instructionId = confirmation.payout.id;
await assert.rejects(()=>api.action(`/mod/payouts/${instructionId}/approve`,{}), e=>e?.data?.error?.message==='Senior moderator access required.');
api.switchRole('SENIOR_MODERATOR');
const approval = await api.action(`/mod/payouts/${instructionId}/approve`,{});
assert.equal(approval.status, 'QUEUED');
assert.equal(api.getDemoState().approvals[0].status, 'QUEUED', 'approval queues instruction but does not claim provider settlement');

api.reset();api.switchRole('SUPPLIER');
const draft=await api.createTransaction({buyer_contact:{phone:'+2348030000000'},delivery:{destination_state:'Rivers',city:'Port Harcourt',expected_within_days:4,fee_payer:'BUYER',delivery_fee_kobo:0},items:[{description:'Item one',specification:'Exact agreed specification',condition:'Brand new',quantity:2,unit_price_kobo:1000000,conditions:[{code:'SPEC_MATCH',kind:'REJECTION',text:'Must match agreed specification'}]},{description:'Item two',specification:'Second item specification',condition:'New',quantity:1,unit_price_kobo:500000,conditions:[{code:'SPEC_MATCH',kind:'REJECTION',text:'Must match agreed specification'}]}],general_terms:'Demo agreement terms.'});
assert.equal(draft.items.length,2,'multi-item transaction drafts are supported');
const sent=await api.action(`/transactions/${draft.id}/send`,{});
assert.ok(sent.invitation_url);
const token=new URL('https://demo.test'+sent.invitation_url).searchParams.get('invite');
api.switchRole('BUYER');
const invite=await api.invitation(token);assert.equal(invite.reference,draft.reference);
await api.acceptInvitation(token);
const acceptedInvite=await api.transaction(draft.id);assert.equal(acceptedInvite.status,'AWAITING_BUYER_AGREEMENT');
const agreementBody={agreement_version_id:draft.agreement_version_id,content_hash:draft.content_hash};
const agreementKey={'Idempotency-Key':'agreement-confirm-once'};
await api.action(`/transactions/${draft.id}/agreement/confirm`,agreementBody,agreementKey);
const auditAfterAgreement=api.getDemoState().audit.filter(x=>x.action==='AGREEMENT_CONFIRMED').length;
await api.action(`/transactions/${draft.id}/agreement/confirm`,agreementBody,agreementKey);
assert.equal(api.getDemoState().audit.filter(x=>x.action==='AGREEMENT_CONFIRMED').length,auditAfterAgreement,'replayed agreement confirmation does not duplicate the event');
const paymentAttempt=await api.action(`/transactions/${draft.id}/payments`,{}, {'Idempotency-Key':'invite-flow-payment'});
assert.equal(paymentAttempt.status,'PENDING');
assert.equal((await api.transaction(draft.id)).status,'AWAITING_PAYMENT');
api.reset();const registration=await api.register({display_name:'Demo Buyer',email:'demo@example.test',phone:'',password:'demo-password-123',accepted_terms:true});assert.equal(registration.verification_required,true);const verified=await api.verifyOtp('demo@example.test','123456');assert.equal(verified.user.display_name,'Demo Buyer');assert.equal(verified.user.role,'BUYER');
console.log('SupplyKey smoke checks passed: enums, role-scoped lists, registration/OTP, multi-item invitation and agreement flow, idempotent pending payment with duplicate-body protection, replay-safe agreement confirmation, delivery evidence, partial dispatch/receipt, rejection/return/refund instruction, moderator case review and senior second approval without simulated settlement.');
